#!/usr/bin/env python3
"""Emit the real auton sources as a JS module for the browser to draw.

    python sim/auton_sources.py [out.js]

sim/bridge/bridge.cpp exports the C++ symbol behind each entry in its auton
dropdown. This writes the matching function text out of src/gamespecific/autons/
keyed by that symbol, so the front end can parse a compiled auton's route and
draw it -- the wasm and the source it plans from come out of the same build, so
they cannot drift.
"""
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUTONS = os.path.join(ROOT, "src", "gamespecific", "autons")
DEFAULT_OUT = os.path.join(ROOT, "sim", "web", "auton_sources.js")

# `void autonName() {`, at any indentation.
SIGNATURE = re.compile(r"^[ \t]*void[ \t]+(auton\w*)[ \t]*\([ \t]*(?:void)?[ \t]*\)[ \t]*\{",
                       re.MULTILINE)

# `void autonBlue3Pin() { reflect(autonRed3Pin); }` -- the whole body. A mirror
# has no motions of its own, so there is nothing here to draw a plan from: the
# parser reads it as zero commands, which is useless to the front end and
# indistinguishable from a routine it failed to understand. Emitting the red
# body under the blue name would be worse -- the drawn path would be the
# unmirrored route, which is a wrong answer rather than a missing one.
REFLECT_ONLY = re.compile(r"\{\s*reflect\s*\(\s*auton\w*\s*\)\s*;\s*\}\s*$")


def blank_noncode(text):
    """Same length, with comments and literals blanked, so brace counting is
    not thrown by a `{` inside a string or a commented-out line."""
    out = list(text)
    i, n = 0, len(text)
    while i < n:
        two = text[i:i + 2]
        if two == "//":
            while i < n and text[i] != "\n":
                out[i] = " "
                i += 1
        elif two == "/*":
            while i < n and text[i:i + 2] != "*/":
                if text[i] != "\n":
                    out[i] = " "
                i += 1
            for j in range(i, min(i + 2, n)):
                out[j] = " "
            i += 2
        elif text[i] in "\"'":
            quote = text[i]
            out[i] = " "
            i += 1
            while i < n and text[i] != quote:
                if text[i] == "\\" and i + 1 < n:
                    out[i] = " "
                    i += 1
                if i < n and text[i] != "\n":
                    out[i] = " "
                i += 1
            if i < n:
                out[i] = " "
                i += 1
        else:
            i += 1
    return "".join(out)


def match_brace(scan, start):
    """Index just past the `}` closing the `{` at `start`, or -1."""
    depth = 0
    for i in range(start, len(scan)):
        if scan[i] == "{":
            depth += 1
        elif scan[i] == "}":
            depth -= 1
            if depth == 0:
                return i + 1
    return -1


def harvest(path):
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        text = fh.read()
    scan = blank_noncode(text)

    found = {}
    for m in SIGNATURE.finditer(scan):
        open_brace = scan.index("{", m.start())
        end = match_brace(scan, open_brace)
        if end == -1:
            continue
        body = text[m.start():end].replace("\r\n", "\n").rstrip()
        if REFLECT_ONLY.search(blank_noncode(body)):
            continue
        found[m.group(1)] = body
    return found


def main():
    out_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_OUT

    sources = {}
    for base, dirs, files in os.walk(AUTONS):
        # Calibration routines drive by hand off controller input, so there is
        # no route to plan and they only bloat the module.
        dirs[:] = [d for d in dirs if d != "tuning"]
        for name in sorted(files):
            if name.endswith(".cpp"):
                sources.update(harvest(os.path.join(base, name)))

    body = ",\n".join("  %s: %s" % (json.dumps(k), json.dumps(v))
                      for k, v in sorted(sources.items()))
    js = ("// Generated by sim/auton_sources.py -- do not edit.\n"
          "// The auton function bodies this build was compiled from, keyed by\n"
          "// the symbol sim_auton_symbol() reports.\n\n"
          "export const AUTON_SOURCES = {\n%s\n};\n" % body)

    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(js)

    print("  %-28s %d autons" % (os.path.relpath(out_path, ROOT), len(sources)))


if __name__ == "__main__":
    main()
